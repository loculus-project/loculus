// Generates src/services/backend/openapi.d.ts from the backend's OpenAPI spec, whose path is the first argument.
// Run via `npm run generate-backend-api`, which first exports the spec from the backend.
import fs from 'node:fs';
import path from 'node:path';

import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const specPath = process.argv[2];
if (specPath === undefined) {
    throw new Error('Usage: node scripts/generateBackendApiTypes.mjs <path to openapi.json>');
}
const outputPath = new URL('../src/services/backend/openapi.d.ts', import.meta.url);

const blob = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier('Blob'));
const nullType = ts.factory.createLiteralTypeNode(ts.factory.createNull());

const ast = await openapiTS(JSON.parse(fs.readFileSync(path.resolve(specPath), 'utf8')), {
    // file uploads (multipart/form-data) are typed as `string` by default
    transform(schemaObject) {
        if (schemaObject.format === 'binary') {
            const types = Array.isArray(schemaObject.type) ? schemaObject.type : [schemaObject.type];
            return types.includes('null') ? ts.factory.createUnionTypeNode([blob, nullType]) : blob;
        }
        return undefined;
    },
});

const header = `/**
 * This file was auto-generated by scripts/generateBackendApiTypes.mjs from the backend's OpenAPI spec.
 * Do not make direct changes to the file. Run \`npm run generate-backend-api\` instead.
 */

`;
fs.writeFileSync(outputPath, header + astToString(ast));
